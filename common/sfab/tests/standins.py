"""Stand-ins for the commands that reach a real device, so the script tests run offline.

session.sh, replay.sh, panos.sh and fw-api.sh call sshpass, ssh and docker by name. The script
tests put a directory of stand-ins first on PATH, so those names never reach a real switch,
firewall or docker daemon: without them a test would open a real SSH session to a lab address
and wait out the scripts' own timeouts (minutes) when the address does not answer.

    bin_dir = standins.make_bin(tmp / "bin", {"sshpass": FAKE_SSHPASS, "ssh": standins.REFUSE})
    env = dict(os.environ, PATH=standins.path_with(bin_dir))
    standins.check(env, bin_dir, ("sshpass", "ssh", "docker"))

check() asks bash which file each name resolves to under that PATH, and fails at once when one
is not the stand-in (a temporary directory mounted noexec, for instance), so a test can never
fall through to the real command.
"""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

# A stand-in that refuses: any call means a script reached for a real device.
REFUSE = """#!/bin/sh
echo "stand-in $(basename "$0"): the tests never reach a real device ($*)" >&2
exit 255
"""

# A docker that answers nothing: no container is known, so no credential is read from one.
NO_DOCKER = """#!/bin/sh
exit 1
"""

# What every script test must shadow.
DEVICE_COMMANDS = ("sshpass", "ssh", "docker")

# The longest a script under test may take before the test fails instead of stalling.
SCRIPT_TIMEOUT_S = 60
# The scripts' own session timeouts, cut down so one stray session cannot stall the run.
SESSION_ENV = {"SFAB_SESSION_TIMEOUT": "20", "PANOS_TIMEOUT": "20"}

# Docker's resolv.conf for a container on a user-defined network, in the shape Docker writes it,
# with a stand-in search domain (.invalid, RFC 6761) where the lab host's own domain would be and a
# documentation address for the host's upstream resolver.
DOCKER_RESOLV_CONF = """# Generated by Docker Engine.
# This file can be edited; Docker Engine will not make further changes once it
# has been modified.

nameserver 127.0.0.11
search lab-host.invalid
options edns0 trust-ad ndots:0

# Based on host file: '/etc/resolv.conf' (internal resolver)
# ExtServers: [192.0.2.53]
# Overrides: []
# Option ndots from: internal
"""


def make_bin(directory: Path, scripts: dict[str, str]) -> Path:
    """Write each stand-in into directory (made if missing), executable; REFUSE for any device
    command not given, NO_DOCKER for docker."""
    directory.mkdir(parents=True, exist_ok=True)
    full = {"sshpass": REFUSE, "ssh": REFUSE, "docker": NO_DOCKER}
    full.update(scripts)
    for name, body in full.items():
        p = directory / name
        p.write_text(body, encoding="utf-8")
        p.chmod(0o755)
    return directory


def path_with(directory: Path, base: str | None = None) -> str:
    """PATH with directory first."""
    rest = os.environ.get("PATH", "") if base is None else base
    return f"{directory}{os.pathsep}{rest}" if rest else str(directory)


def resolve(env: dict, names=DEVICE_COMMANDS) -> dict[str, str]:
    """What bash runs for each name under env's PATH (empty when nothing is found)."""
    script = 'for n in "$@"; do printf "%s=%s\\n" "$n" "$(command -v "$n" || true)"; done'
    r = subprocess.run(["bash", "-c", script, "resolve", *names], env=env, capture_output=True, text=True,
                       timeout=30)
    out = {}
    for line in r.stdout.splitlines():
        k, _, v = line.partition("=")
        out[k] = v
    return out


def check(env: dict, directory: Path, names=DEVICE_COMMANDS) -> None:
    """Raise AssertionError unless each name resolves to its stand-in in directory."""
    got = resolve(env, names)
    bad = {}
    for n in names:
        have = got.get(n) or ""
        if not have or os.path.realpath(have) != os.path.realpath(directory / n):
            bad[n] = have
        elif not os.access(have, os.X_OK):
            # bash names a file it cannot run when it finds nothing better on PATH
            bad[n] = f"{have}, which cannot be run"
    if bad:
        raise AssertionError(
            "the stand-ins do not shadow the real commands, so a script under test could reach a real device: "
            + ", ".join(f"{n} resolves to {v or 'nothing'}" for n, v in sorted(bad.items()))
            + f" (stand-ins in {directory}; is that directory on a noexec mount? set TMPDIR elsewhere)")


def run_resolver(bash: str, script: Path, resolv: Path, env: dict) -> subprocess.CompletedProcess:
    """An init script's resolver() alone, for real (no dry run), on the file RESOLV: the function
    is cut from the script's text and run under ENV, so the rewrite is tested without a container."""
    m = re.search(r"^resolver\(\) \{\n.*?^\}\n", Path(script).read_text(), re.M | re.S)
    if m is None:
        raise AssertionError(f"{script}: no resolver() function")
    prog = f'set -euo pipefail\nDRY=0\nRESOLV_CONF="$1"\n{m.group(0)}resolver\n'
    full = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LC_ALL": "C", **env}
    return subprocess.run([bash, "-c", prog, "resolver", str(resolv)], env=full, capture_output=True, text=True,
                          timeout=SCRIPT_TIMEOUT_S)
