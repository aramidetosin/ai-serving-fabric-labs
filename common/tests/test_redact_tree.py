    # namecheck-summary: a saved namecheck output cut to the lines the audit saves today

    def saved_namecheck(self, text):
        f = self.set / "repo" / "namecheck.txt"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
        return f

    def test_namecheck_summary_cuts_to_the_saved_form(self):
        f = self.saved_namecheck(
            f"x/a.txt:3: warn name (digest): a line with {WORD} in it\n"
            f"lab/audits/old/repo/namecheck.txt:1: warn name (digest): x/a.txt:3: warn name (digest): {WORD}\n"
            f"x/b.txt:9: fail name: {WORD}2 here\n"
            f"x/c.txt:4: warn name: {WORD}\n"
            "namecheck: 12 files, 1 fail, 3 warn (digests)\n")
        rc, out = self.run_tool("--class", "namecheck-summary", str(self.audits))
        self.assertEqual(rc, 0, out)
        self.assertEqual(f.read_text(), "x/b.txt:9: fail name\nnamecheck: 12 files, 1 fail, 3 warn (digests)\n")
        self.assertNotIn(WORD, out, "the output names no text the file quoted")
        self.assertIn("repo/namecheck.txt: namecheck-summary: cut from 5 lines to 2", out)
        led = (self.set / "REDACTIONS.md").read_text()
        self.assertIn("| repo/namecheck.txt | 5 | 3, 5 | namecheck-summary |", led)
        self.assertIn("| namecheck-summary |", led)
        self.assertNotIn("| File | Line | Class |", led, "no marker table without a marker")
        self.assertNotIn(WORD, led)
        once = {p: p.read_bytes() for p in self.set.rglob("*") if p.is_file()}
        rc, out = self.run_tool("--class", "namecheck-summary", str(self.audits))
        self.assertEqual(rc, 0, out)
        self.assertIn("cut 0 files of 1", out)
        self.assertEqual({p: p.read_bytes() for p in self.set.rglob("*") if p.is_file()}, once, "a second run changes nothing")
        rc, out = self.run_tool("--check", "--class", "namecheck-summary", str(self.audits))
        self.assertEqual(rc, 0, out)

    def test_namecheck_summary_keeps_a_fail_line_that_quotes_a_warn_line(self):
        # an unmasked fail line on an earlier saved output quotes that output's warn line
        f = self.saved_namecheck(
            f"x/repo/namecheck.txt:1: fail name: y.txt:2: warn name (digest): {WORD}\n"
            f"y.txt:2: warn name (digest): {WORD}\n"
            "namecheck: 2 files, 1 fail, 1 warn (digests)\n")
        rc, out = self.run_tool("--class", "namecheck-summary", str(self.audits))
        self.assertEqual(rc, 0, out)
        self.assertEqual(f.read_text(), "x/repo/namecheck.txt:1: fail name\nnamecheck: 2 files, 1 fail, 1 warn (digests)\n")
        self.assertIn("| repo/namecheck.txt | 3 | 1, 3 | namecheck-summary |", (self.set / "REDACTIONS.md").read_text())
        self.assertNotIn(WORD, out)

    def test_namecheck_summary_refuses_a_fail_count_it_cannot_keep(self):
        text = f"x/b.txt:9: fail name: {WORD}\nnamecheck: 2 files, 2 fail, 0 warn\n"
        f = self.saved_namecheck(text)
        rc, out = self.run_tool("--class", "namecheck-summary", str(self.set))
        self.assertEqual(rc, 1, out)
        self.assertIn("repo/namecheck.txt:2: a line the audit would not save in this form", out)
        self.assertEqual(f.read_text(), text)
        self.assertNotIn(WORD, out)

    def test_namecheck_summary_leaves_the_saved_form_alone(self):
        f = self.saved_namecheck("namecheck: 3349 files, 0 fail, 38920 warn (digests)\n")
