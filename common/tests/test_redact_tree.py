        self.saved_namecheck(f"x:1: warn name: {WORD}\nnamecheck: 1 files, 0 fail, 1 warn (digests)\n")
        rc, out = self.run_tool("--class", "namecheck-summary", str(self.audits))
        self.assertEqual(rc, 0, out)
        led = (self.set / "REDACTIONS.md").read_text()
        self.assertIn("| ops-client/07_resolv_conf.txt | 4 | host-search-domain |", led, "a cut keeps the markers' rows")
        self.assertIn("| repo/namecheck.txt | 2 | 2 | namecheck-summary |", led)
        # a later marker run, over the set or over one file only, keeps the cut file's row
        uplink = self.set / "uplink-rtr.txt"
        uplink.write_text("Linux version 9.9.9-1-stand-in\n")
