"""Tests for common/audit/redact_tree.py: in-place class markers in recorded result sets, and the
namecheck-summary cut of a set's saved namecheck output."""

from __future__ import annotations

import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "common" / "audit"))

import redact_tree  # noqa: E402

# stand-ins for a lab host's search domain: an account label and the zone after it
LABEL = "acct7label"
DOMAIN = LABEL + ".zone.test"
WHERE = r"^\s*(search|domain)\s"
# a stand-in for a word a saved namecheck output quoted
WORD = "quotedword"
RESOLV = ("# Generated by Docker Engine.\n\nnameserver 127.0.0.11\n"
          f"search {DOMAIN}\noptions edns0 trust-ad ndots:0\n\n# Based on host file: '/etc/resolv.conf'\n")


class RedactTreeTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.d = Path(self.tmp.name)
        self.lits = self.d / "secrets.txt"
        self.lits.write_text(f"# a comment\n\nOtherSecret99\n{LABEL}\n")
        self.audits = self.d / "lab" / "audits"
        self.set = self.audits / "x_audit_20261020T000000Z"
        (self.set / "ops-client").mkdir(parents=True)

    def tearDown(self):
        self.tmp.cleanup()

    def run_tool(self, *args):
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            rc = redact_tree.main(list(args))
        return rc, out.getvalue()

    def search_args(self, *paths):
        return ("--class", "host-search-domain", "--literals", str(self.lits), "--where", WHERE, "--token",
                *(str(p) for p in paths))

    def test_replaces_in_place_and_is_idempotent(self):
        f = self.set / "ops-client" / "07_resolv_conf.txt"
        f.write_text(RESOLV)
        g = self.set / "commands.txt"
        g.write_text("### ops-client\n+ sh -c cat /etc/resolv.conf\n" + RESOLV + "### next\n")
        rc, out = self.run_tool(*self.search_args(self.audits))
        self.assertEqual(rc, 0, out)
        t = f.read_text()
        self.assertEqual(t.count("\n"), RESOLV.count("\n"), "no line added or removed")
        self.assertEqual(t.splitlines()[3], "search [redacted: host-search-domain]", "the whole domain goes")
        self.assertEqual(t.splitlines()[:3] + t.splitlines()[4:], RESOLV.splitlines()[:3] + RESOLV.splitlines()[4:])
        self.assertNotIn(LABEL, g.read_text())
        self.assertNotIn(LABEL, out, "the output names no replaced text")
        self.assertIn("ops-client/07_resolv_conf.txt:4: host-search-domain", out)
        led = (self.set / "REDACTIONS.md").read_text()
        self.assertIn("| ops-client/07_resolv_conf.txt | 4 | host-search-domain |", led)
        self.assertIn("| commands.txt | 6 | host-search-domain |", led)
        self.assertNotIn(LABEL, led)
        once = {p: p.read_bytes() for p in self.set.rglob("*") if p.is_file()}
        rc, out = self.run_tool(*self.search_args(self.audits))
        self.assertEqual(rc, 0, out)
        self.assertIn("changed 0 lines", out)
        self.assertEqual({p: p.read_bytes() for p in self.set.rglob("*") if p.is_file()}, once, "a second run changes nothing")
        rc, out = self.run_tool("--check", *self.search_args(self.audits))
        self.assertEqual(rc, 0, out)

    def test_check_changes_nothing(self):
        f = self.set / "ops-client" / "07_resolv_conf.txt"
        f.write_text(RESOLV)
        rc, out = self.run_tool("--check", *self.search_args(self.set))
        self.assertEqual(rc, 1, out)
        self.assertIn("would change", out)
        self.assertEqual(f.read_text(), RESOLV)
        self.assertFalse((self.set / "REDACTIONS.md").exists())

    def test_literal_left_outside_where_and_in_binary(self):
        (self.set / "notes.txt").write_text(f"a line that names {DOMAIN} in prose\n")
        (self.set / "cap.pcap").write_bytes(b"\xd4\xc3\xb2\xa1\0\0" + LABEL.encode() + b"\0")
        rc, out = self.run_tool(*self.search_args(self.set))
        self.assertEqual(rc, 1, out)
        self.assertIn("notes.txt:1: a literal is left", out)
        self.assertIn("cap.pcap (binary, left alone): a literal is left", out)
        self.assertIn(DOMAIN, (self.set / "notes.txt").read_text(), "--where kept the prose line as it was")
        self.assertNotIn(LABEL, out)

    def test_literal_in_another_case(self):
        # a device may print a name in capitals: it is the same name, replaced or reported
        f = self.set / "ops-client" / "07_resolv_conf.txt"
        f.write_text(f"search {DOMAIN.upper()}\n")
        (self.set / "notes.txt").write_text(f"a line that names {LABEL.title()} in prose\n")
        rc, out = self.run_tool(*self.search_args(self.set))
        self.assertEqual(rc, 1, out)
        self.assertEqual(f.read_text(), "search [redacted: host-search-domain]\n", "the whole name goes")
        self.assertIn("notes.txt:1: a literal is left", out)
        self.assertNotIn(LABEL, out.lower())

    def test_binary_holding_the_name_in_dns_wire_form(self):
        # the literals file holds the domain; a capture carries it as DNS labels, whole or compressed
        lits = self.d / "domain.txt"
        lits.write_text(DOMAIN + "\n")
        wire = b"".join(bytes([len(x)]) + x.encode() for x in DOMAIN.split("."))
        head = b"\xd4\xc3\xb2\xa1\0\0"
        (self.set / "whole.pcap").write_bytes(head + b"\x03www" + wire.upper() + b"\0")
        (self.set / "compressed.pcap").write_bytes(head + bytes([len(LABEL)]) + LABEL.encode() + b"\xc0\x0c")
        (self.set / "other.pcap").write_bytes(head + b"\x03www\x04zone\x04test\0")
        args = ("--class", "host-search-domain", "--literals", str(lits), "--where", WHERE, "--token", str(self.set))
        rc, out = self.run_tool(*args)
        self.assertEqual(rc, 1, out)
        self.assertIn("whole.pcap (binary, left alone): a literal is left", out)
        self.assertIn("compressed.pcap (binary, left alone): a literal is left", out)
        self.assertNotIn("other.pcap", out, "the zone's labels alone are not the literal")
        self.assertNotIn(LABEL, out.lower())
        pats = [rx.pattern for rx in redact_tree.wire_forms("ab.zone.test")]
        self.assertEqual(pats, [b"\x02ab\x04zone\x04test", b"\x02ab" + redact_tree.POINTER,
                                b"\x02ab\x04zone" + redact_tree.POINTER], "a short first label is not searched alone")
        self.assertEqual(redact_tree.wire_forms(LABEL), [], "a literal that is not a dotted name has no wire form")

    def test_short_first_label_found_compressed(self):
        # a literal whose first label is shorter than WIRE_LABEL_MIN, spelled as a compressed name
        # (its first labels, then a pointer back to the rest), is found; the same labels followed
        # by anything but a pointer, or a one-character first label alone before a pointer, are not
        rules = redact_tree.Rules("x", ["ab.zone.test", "q.zone.test"])
        head = b"\xd4\xc3\xb2\xa1\0\0\x03www\x04zone\x04test\0"
        for tail in (b"\x02AB\xc0\x10", b"\x02ab\xff\x00", b"\x02ab\x04zone\xc0\x15", b"\x01q\x04zone\xc0\x15",
                     b"\x02ab\x04zone\x04test\0"):
            self.assertTrue(rules.in_binary(head + tail), tail)
        for tail in (b"\x02ab\x05other\0", b"\x02ab\x7f", b"\x01q\xc0\x10", b"\x02ac\xc0\x10", b"\x03xab\xc0\x10"):
            self.assertFalse(rules.in_binary(head + tail), tail)

    def test_literal_hits_finds_every_form_and_names_none(self):
        # the gate's scan: every file of a set, text, compressed and binary, in --check's forms
        import gzip
        other = "OtherSecret99"
        wire = b"".join(bytes([len(x)]) + x.encode() for x in DOMAIN.split("."))
        head = b"\xd4\xc3\xb2\xa1\0\0"
        (self.set / "ops-client" / "07_resolv_conf.txt").write_text(f"nameserver 127.0.0.11\nsearch {DOMAIN.upper()}\n")
        (self.set / "captures").mkdir()
        (self.set / "captures" / "1-dns.pcap").write_bytes(head + bytes([len(LABEL)]) + LABEL.encode() + b"\xc0\x0c")
        (self.set / "captures" / "2-dns.pcap").write_bytes(head + b"\x03www" + wire.upper() + b"\0")
        (self.set / "captures" / "3-dns.pcap").write_bytes(head + b"\x03www\x04zone\x04test\0")
        (self.set / "commands.txt.gz").write_bytes(gzip.compress(f"### x\nok\nlogin {other.lower()}\n".encode(), mtime=0))
        (self.set / f"notes-{DOMAIN}.txt").write_text("nothing here\n")
        # the first label alone counts only in a binary file, as --check counts it
        (self.set / "clean.txt").write_text(f"{LABEL} alone\n")
        hits = redact_tree.literal_hits(str(self.set), [DOMAIN, other])
        self.assertEqual(hits, [
            "commands.txt.gz:3: a literal",
            "notes-[redacted: literal].txt: a literal in the path",
            "captures/1-dns.pcap: a literal (binary, as text or in DNS wire form)",
            "captures/2-dns.pcap: a literal (binary, as text or in DNS wire form)",
            "ops-client/07_resolv_conf.txt:2: a literal",
        ])
        for h in hits:
            self.assertNotIn(LABEL, h.lower())
            self.assertNotIn(other.lower(), h.lower())
        self.assertEqual(redact_tree.literal_hits(str(self.set), []), [], "no literal, nothing to find")
        self.assertEqual(redact_tree.literal_hits(str(self.set / "ops-client"), ["absent-literal"]), [])

